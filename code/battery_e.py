# Detection track (build_samples_e_detect.py): the SAME questions/answers, but the sample carries the target model's actual
# choice in meta.model_choice ("A"/"B" for option legs, "yes"/"no" for grounded legs) and label = label_detect
# (option legs: the model picked the flagged option; grounded legs: the model accepted an unsupported claim/summary).
# Every understanding strategy s = P(option_B is bad) / P(unsupported) is turned into a detection risk in code:
#   option legs:   risk = s if the model chose B else 1 - s        (P(the chosen option is the bad one))
#   grounded legs: risk = s if the model answered "yes" else 0.0   (a rejected claim cannot be an accepted-unsupported case)
# None (abstain) stays None. heuristic:consistency stays a diagnostic.
STRATEGY_REQUIRES.update({f"{leg}__detect": dict(v) for leg, v in list(STRATEGY_REQUIRES.items())})
CONFIG_ROLE.update({f"{leg}__detect": "main" for leg in ALL_LEGS})


def _is_detect(sample):
    return (sample.get("meta") or {}).get("variant") == "detect"


def config_id(sample):
    """Config id used to index STRATEGY_REQUIRES: the leg, or <leg>__detect for detection-track samples."""
    return f"{sample['leg']}__detect" if _is_detect(sample) else sample["leg"]


def strategies(sample, ans):
    """Every strategy resolved for this leg; None when any required answer is missing (never a fabricated 0).
    Detection-track samples (meta.variant == "detect") get the understanding value mapped onto the model's actual choice."""
    ans = ans or {}
    out = {}
    for name, (req, fn) in _RESOLVED[sample["leg"]].items():
        if any(ans.get(q) is None for q in req):
            out[name] = None
            continue
        v = fn(ans)
        out[name] = None if v is None else min(1.0, max(0.0, float(v)))
    if _is_detect(sample):
        choice = str((sample.get("meta") or {}).get("model_choice", "")).strip().upper()
        grounded = sample["leg"] in GROUNDED_LEGS
        for name, v in out.items():
            if v is None or name.startswith("heuristic:consistency"):
                continue
            if grounded:
                out[name] = v if choice == "YES" else 0.0
            else:
                out[name] = v if choice == "B" else (1.0 - v if choice == "A" else None)
    return out


