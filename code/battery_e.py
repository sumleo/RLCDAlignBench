# naive Choice: one row name shared by both families, bound per family to that family's qid
# (choice_action: naive_choice over the two options, positive = option_B; grounded: misbehaves_choice, positive = yes).
_NAIVE_CHOICE = {"choice_action": ("naive_choice", "option_B", ("option_A",)),
                 "grounded": ("misbehaves_choice", "yes", ("no",))}


def _family(leg):
    return "grounded" if leg in GROUNDED_LEGS else "choice_action"


def _leg_qids(leg):
    state = {"summary": ""} if leg == "summedits" else {"claim": ""}
    return set(questions({"leg": leg, "state": state}))


def _resolve(leg):
    """{name: (required qids, fn)} for one leg: every registered strategy whose qids all exist in the leg's question set,
    plus the two naive Choice rows bound to the family's qid."""
    qids = _leg_qids(leg)
    out = {name: (req, fn) for name, (req, fn) in _REG.items() if set(req) <= qids}
    qid, pos, negs = _NAIVE_CHOICE[_family(leg)]
    out["naive:choice"] = ([qid], lambda a, qid=qid, pos=pos: _cprob(a, qid, pos))
    out["naive:choice_argmax"] = ([qid], lambda a, qid=qid, pos=pos, negs=negs: _cargmax(a, qid, pos, negs))
    return out


