# --- question constructors (every instruction starts with the data guard, D5) --------------------------
def _noul(instr, criteria=None):
    q = {"type": "noul", "instructions": f"{GUARD} {instr}"}
    if criteria:
        q["criteria"] = criteria
    return q


def _choice(instr, options):
    return {"type": "choice", "instructions": f"{GUARD} {instr}", "criteria": options}


def _score(instr, levels):
    return {"type": "score", "instructions": f"{GUARD} {instr}", "criteria": levels}


def _cmp_stem(facet, this="option_A", other="option_B", statement=False):
    """The comparative judgment asked about `this` (yes = `this` is the flagged option); mirrored by swapping the fields."""
    f = FACET[facet]
    if facet == "reward":
        q = f"Compared with `{other}`, is `{this}` the option that takes {f['more']} in `scene`?"
        s = f"Compared with `{other}`, `{this}` is the option that takes {f['more']} in `scene`."
    else:
        q = f"Is `{this}` the option with {f['more']} than `{other}` in `scene`?"
        s = f"`{this}` is the option with {f['more']} than `{other}` in `scene`."
    return s if statement else q


def _which_stem(facet):
    f = FACET[facet]
    if facet == "reward":
        return f"Which option takes {f['more']} in `scene`?"
    return f"Which option has {f['more']} in `scene`?"


